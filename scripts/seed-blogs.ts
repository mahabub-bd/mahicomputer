async function main() {
  // Resolve each post's author by Instructor name (fails loudly on a typo
  // rather than silently saving without an author).
  const instructors = await prisma.instructor.findMany({
    select: { id: true, name: true },
  });
  const byName = new Map(instructors.map((i) => [i.name.trim(), i.id]));
  const authorIdBySlug = new Map<string, string>();
  for (const post of POSTS) {
    const id = byName.get(post.authorName);
    if (!id) throw new Error(`Instructor not found: "${post.authorName}"`);
    authorIdBySlug.set(post.slug, id);
  }

  const existing = await prisma.post.findMany({
    select: { id: true, slug: true, authorId: true },
  });
  const bySlug = new Map(existing.map((p) => [p.slug, p]));
  const missing = POSTS.filter((p) => !bySlug.has(p.slug));

  for (const { authorName, ...post } of missing) {
    await prisma.post.create({
      data: { ...post, authorId: authorIdBySlug.get(post.slug)!, published: true },
    });
    console.log(`created: ${post.slug} (author: ${authorName})`);
  }

  // Backfill authors for posts that were seeded before the author relation.
  let linked = 0;
  for (const post of POSTS) {
    const row = bySlug.get(post.slug);
    if (row && !row.authorId) {
      await prisma.post.update({
        where: { id: row.id },
        data: { authorId: authorIdBySlug.get(post.slug)! },
      });
      linked++;
      console.log(`author linked: ${post.slug} -> ${post.authorName}`);
    }
  }

  if (missing.length === 0 && linked === 0) {
    console.log("all blog posts already present with authors — skip");
  } else {
    console.log(
      `done: ${missing.length} created, ${linked} authors linked (table has ${existing.length + missing.length} total)`
    );
  }
  await prisma.$disconnect();
}

main().catch((e) => {
  console.error("ERROR code:", e.code);
  console.error("ERROR full:", JSON.stringify({ message: e.message, clientVersion: e.clientVersion, cause: String(e.cause ?? "") }, null, 2));
  process.exit(1);
});
