async function main() {
  const existing = await prisma.faq.findMany({ select: { question: true } });
  const existingQuestions = new Set(existing.map((f) => f.question));
  const missing = FAQS.filter((f) => !existingQuestions.has(f.q));

  if (missing.length === 0) {
    console.log("no new faqs to insert — skip");
    return;
  }

  const startOrder = await prisma.faq.count();
  await prisma.faq.createMany({
    data: missing.map((f, i) => ({
      question: f.q,
      answer: f.a,
      order: startOrder + i,
    })),
  });
  console.log("seeded", missing.length, "new faqs (table has", existing.length + missing.length, "total)");
  await prisma.$disconnect();
}
main().catch((e) => {
  console.error("ERROR code:", e.code);
  console.error("ERROR full:", JSON.stringify({ message: e.message, clientVersion: e.clientVersion, cause: String(e.cause ?? "") }, null, 2));
  process.exit(1);
});
